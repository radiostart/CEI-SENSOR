const sensor_glyph_t *sensor_glyph_get(sensor_glyph_id_t id) {
  if ((int)id < 0 || id >= SENSOR_GLYPH_COUNT)
    return 0;
  return &g_glyphs[id];
}

sensor_glyph_id_t sensor_glyph_lookup(char c) {
  if (c >= '0' && c <= '9')
    return (sensor_glyph_id_t)(SENSOR_GLYPH_0 + (c - '0'));
  switch (c) {
  case '.':
    return SENSOR_GLYPH_DOT;
  case '^':
    return SENSOR_GLYPH_DEG18; // degree sign
  case 'C':
    return SENSOR_GLYPH_C18;
  case '%':
    return SENSOR_GLYPH_PCT18;
  case '-':
    return SENSOR_GLYPH_HYPHEN;
  default:
    return SENSOR_GLYPH_DOT;
  }
}
